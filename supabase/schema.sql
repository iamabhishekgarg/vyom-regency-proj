-- ============================================================
-- properties
-- ============================================================

create table if not exists public.properties (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  location text,
  price text,
  size text,
  status text default 'available',
  description text,
  features text[] default '{}',
  image_url text,
  created_at timestamptz not null default now(),
  display_type text default 'single',
  sort_order integer default 0,
  show_on_home boolean default false,
  brochure_url text,
  gallery_urls text[] default '{}',
  property_type text default 'project',
  meta_title text,
  meta_description text,
  focus_keyword text,
  video_url text,
  registry_type text,
  possession_status text,
  plots_left integer
);

alter table public.properties enable row level security;

drop policy if exists "Public can view properties" on public.properties;
create policy "Public can view properties" on public.properties for select using (true);

drop policy if exists "Authenticated can insert properties" on public.properties;
create policy "Authenticated can insert properties" on public.properties for insert with check (auth.role() = 'authenticated');

drop policy if exists "Authenticated can update properties" on public.properties;
create policy "Authenticated can update properties" on public.properties for update using (auth.role() = 'authenticated');

drop policy if exists "Authenticated can delete properties" on public.properties;
create policy "Authenticated can delete properties" on public.properties for delete using (auth.role() = 'authenticated');

-- backfill: rows that were created before property_type existed and are
-- named like an individual plot rather than a multi-plot project
update public.properties set property_type = 'individual'
where property_type is null and name ilike 'individual%';


