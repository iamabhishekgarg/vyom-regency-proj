-- ============================================================
-- Storage buckets (all public-read; writes require an authenticated
-- session, enforced by the same "authenticated" storage policies)
-- ============================================================

insert into storage.buckets (id, name, public)
values
  ('properties', 'properties', true),
  ('blog', 'blog', true),
  ('gallery', 'gallery', true),
  ('testimonials', 'testimonials', true),
  ('hero-banners', 'hero-banners', true),
  ('brochures', 'brochures', true)
on conflict (id) do nothing;

drop policy if exists "Public can read storage objects" on storage.objects;
create policy "Public can read storage objects" on storage.objects
  for select using (bucket_id in ('properties', 'blog', 'gallery', 'testimonials', 'hero-banners', 'brochures'));

drop policy if exists "Authenticated can manage storage objects" on storage.objects;
create policy "Authenticated can manage storage objects" on storage.objects
  for all using (auth.role() = 'authenticated' and bucket_id in ('properties', 'blog', 'gallery', 'testimonials', 'hero-banners', 'brochures'))
  with check (auth.role() = 'authenticated' and bucket_id in ('properties', 'blog', 'gallery', 'testimonials', 'hero-banners', 'brochures'));
