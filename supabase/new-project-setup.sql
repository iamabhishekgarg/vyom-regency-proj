-- Public (anonymous) can READ: properties, testimonials, blog_posts, site_settings
-- These are shown on the public marketing pages without login.
create policy "Public can view properties" on public.properties for select using (true);
create policy "Public can view testimonials" on public.testimonials for select using (true);
create policy "Public can view blog posts" on public.blog_posts for select using (true);
create policy "Public can view site settings" on public.site_settings for select using (true);

-- Logged-in admin (authenticated) can manage: properties, testimonials, blog_posts, site_settings
create policy "Authenticated can insert properties" on public.properties for insert with check (auth.role() = 'authenticated');
create policy "Authenticated can update properties" on public.properties for update using (auth.role() = 'authenticated');
create policy "Authenticated can delete properties" on public.properties for delete using (auth.role() = 'authenticated');

create policy "Authenticated can insert testimonials" on public.testimonials for insert with check (auth.role() = 'authenticated');
create policy "Authenticated can update testimonials" on public.testimonials for update using (auth.role() = 'authenticated');
create policy "Authenticated can delete testimonials" on public.testimonials for delete using (auth.role() = 'authenticated');

create policy "Authenticated can insert blog posts" on public.blog_posts for insert with check (auth.role() = 'authenticated');
create policy "Authenticated can update blog posts" on public.blog_posts for update using (auth.role() = 'authenticated');
create policy "Authenticated can delete blog posts" on public.blog_posts for delete using (auth.role() = 'authenticated');

create policy "Authenticated can update site settings" on public.site_settings for update using (auth.role() = 'authenticated');

-- Admin-only tables (no public access at all — leads/feedback are private,
-- gallery/settings are only ever read or written from the logged-in admin panel)
create policy "Authenticated can manage gallery" on public.gallery for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "Authenticated can manage leads" on public.leads for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "Authenticated can manage visitor reviews" on public.visitor_reviews for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "Authenticated can manage website feedback" on public.website_feedback for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "Authenticated can manage settings" on public.settings for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

