-- =========================================================
-- TABLES
-- =========================================================

create table public.properties (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null,
  location text,
  price text,
  size text,
  status text default 'available',
  description text,
  features text[],
  image_url text,
  created_at timestamptz default now(),
  display_type text default 'single',
  sort_order integer default 0,
  show_on_home boolean default false
);

create table public.testimonials (
  id bigint generated by default as identity primary key,
  name text not null,
  location text,
  type text,
  rating integer,
  text text not null,
  media_type text default 'text',
  image_url text,
  video_url text,
  source text default 'admin',
  status text default 'approved',
  created_at timestamptz default now()
);

create table public.visitor_reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  email text,
  visited_date date,
  property_name text,
  rating integer,
  experience text,
  suggestions text,
  status text default 'pending',
  created_at timestamptz default now()
);

create table public.website_feedback (
  id bigint generated by default as identity primary key,
  name text,
  email text,
  rating integer,
  experience text,
  suggestions text,
  status text default 'pending',
  created_at timestamptz default now()
);

create table public.blog_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null,
  excerpt text,
  content text,
  category text,
  "categorySlug" text,
  author text,
  date text,
  "readTime" text,
  image text,
  tags text[] default '{}',
  featured boolean default false,
  created_at timestamptz default now()
);

create table public.gallery (
  id bigint generated by default as identity primary key,
  url text not null,
  caption text,
  created_at timestamptz default now()
);

create table public.leads (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null,
  email text,
  city text,
  project text,
  source text default 'website',
  status text default 'new',
  message text,
  created_at timestamptz default now()
);

create table public.settings (
  id integer primary key default 1,
  site_title text,
  site_description text,
  contact_phone text,
  contact_email text,
  address text
);

create table public.site_settings (
  id integer primary key default 1,
  hero_image_key text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

